package osrs.dev.dumper.settings;

import java.text.Normalizer;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes the SettingID source: a class per settings category holding a typed key per row, the options of each dropdown,
 * and the keys a key binding can take.
 */
final class SettingIdWriter
{
    static final String PACKAGE = "com.tonic.data.settings";
    static final String CLASS_NAME = "SettingID";
    private static final String KEY_BINDINGS = "KeyBindings";
    private static final Map<Integer, String> KEY_TYPES = new HashMap<>();

    static
    {
        KEY_TYPES.put(SettingsMenu.KIND_TOGGLE, "ToggleSetting");
        KEY_TYPES.put(SettingsMenu.KIND_SLIDER, "SliderSetting");
        KEY_TYPES.put(SettingsMenu.KIND_DROPDOWN, "DropdownSetting");
        KEY_TYPES.put(SettingsMenu.KIND_KEY_BINDING, "KeyBindingSetting");
        KEY_TYPES.put(SettingsMenu.KIND_NUMBER, "NumberSetting");
        KEY_TYPES.put(SettingsMenu.KIND_ACTION, "ActionSetting");
        KEY_TYPES.put(SettingsMenu.KIND_COLOUR, "ColourSetting");
        KEY_TYPES.put(SettingsMenu.KIND_LIST_EDITOR, "ListEditorSetting");
    }

    private final SettingsMenu menu;

    /**
     * @param menu the menu to write
     */
    SettingIdWriter(SettingsMenu menu)
    {
        this.menu = menu;
    }

    /**
     * @return the source of SettingID
     */
    String source()
    {
        StringBuilder body = new StringBuilder();
        UniqueNames categoryNames = new UniqueNames();
        for (SettingsMenu.Category category : menu.categories())
        {
            category(body, categoryNames.name(className(category.name())), category);
        }
        keyBindings(body);

        return "/* Generated by CacheMapDumper from the cache's settings menu (enum 422). Do not edit. */\n"
                + "package " + PACKAGE + ";\n\n"
                + "/**\n * The settings menu by category, each key typed by the kind of setting it names.\n */\n"
                + "@SuppressWarnings(\"unused\")\n"
                + "public final class " + CLASS_NAME + "\n{\n"
                + "    private " + CLASS_NAME + "()\n    {\n    }\n"
                + body
                + "}\n";
    }

    private void category(StringBuilder out, String className, SettingsMenu.Category category)
    {
        List<SettingsMenu.Entry> entries = new ArrayList<>();
        for (SettingsMenu.Entry entry : category.entries())
        {
            if (!entry.mobileOnly() && !entry.layout())
            {
                entries.add(entry);
            }
        }

        Map<SettingsMenu.Entry, String> names = names(entries);
        out.append("\n    /**\n     * ").append(doc(category.name())).append("\n     */\n")
                .append("    public static final class ").append(className).append("\n    {\n")
                .append("        private ").append(className).append("()\n        {\n        }\n");

        UniqueNames optionClasses = new UniqueNames();
        optionClasses.name(className);
        StringBuilder optionBodies = new StringBuilder();
        for (SettingsMenu.Entry entry : entries)
        {
            String type = KEY_TYPES.get(entry.kind());
            String name = names.get(entry);
            out.append("\n        /**\n         * ").append(doc(entryDoc(entry))).append("\n         */\n")
                    .append("        public static final ").append(type).append(' ').append(name)
                    .append(" = new ").append(type).append('(').append(entry.structId()).append(");\n");
            if (entry.kind() == SettingsMenu.KIND_DROPDOWN && !entry.options().isEmpty())
            {
                dropdownOptions(optionBodies, optionClasses.name(className(name)), name, entry);
            }
        }
        out.append(optionBodies).append("    }\n");
    }

    private void dropdownOptions(StringBuilder out, String className, String key, SettingsMenu.Entry entry)
    {
        out.append("\n        /**\n         * The options of ").append(doc(entry.label())).append(".\n         */\n")
                .append("        public static final class ").append(className).append("\n        {\n")
                .append("            private ").append(className).append("()\n            {\n            }\n");
        UniqueNames scope = new UniqueNames();
        List<String> options = entry.options();
        for (int value = 0; value < options.size(); value++)
        {
            out.append("\n            /**\n             * ").append(doc(options.get(value))).append("\n             */\n")
                    .append("            public static final DropdownOption ").append(scope.name(constant(options.get(value))))
                    .append(" = new DropdownOption(").append(key).append(", ").append(value).append(");\n");
        }
        out.append("        }\n");
    }

    private void keyBindings(StringBuilder out)
    {
        Map<Integer, List<String>> byEnum = new LinkedHashMap<>();
        for (SettingsMenu.Category category : menu.categories())
        {
            for (SettingsMenu.Entry entry : category.entries())
            {
                if (entry.kind() == SettingsMenu.KIND_KEY_BINDING && !entry.mobileOnly() && !entry.options().isEmpty())
                {
                    byEnum.putIfAbsent(entry.optionEnum(), entry.options());
                }
            }
        }

        for (Map.Entry<Integer, List<String>> keys : byEnum.entrySet())
        {
            String className = byEnum.size() == 1 ? KEY_BINDINGS : KEY_BINDINGS + keys.getKey();
            out.append("\n    /**\n     * The keys a key binding can be set to.\n     */\n")
                    .append("    public static final class ").append(className).append("\n    {\n")
                    .append("        private ").append(className).append("()\n        {\n        }\n");
            UniqueNames scope = new UniqueNames();
            List<String> options = keys.getValue();
            for (int value = 0; value < options.size(); value++)
            {
                out.append("\n        /**\n         * ").append(doc(options.get(value))).append("\n         */\n")
                        .append("        public static final KeyBindingOption ").append(scope.name(constant(options.get(value))))
                        .append(" = new KeyBindingOption(").append(value).append(");\n");
            }
            out.append("    }\n");
        }
    }

    /**
     * Names a category's keys from their labels; a label used more than once is prefixed with its section, and any name
     * still taken is suffixed.
     */
    static Map<SettingsMenu.Entry, String> names(List<SettingsMenu.Entry> entries)
    {
        Map<String, Integer> uses = new HashMap<>();
        for (SettingsMenu.Entry entry : entries)
        {
            uses.merge(constant(label(entry)), 1, Integer::sum);
        }

        UniqueNames scope = new UniqueNames();
        Map<SettingsMenu.Entry, String> names = new LinkedHashMap<>();
        for (SettingsMenu.Entry entry : entries)
        {
            String base = constant(label(entry));
            SettingsMenu.Entry section = entry.section();
            if (uses.get(base) > 1 && section != null && section.label() != null)
            {
                base = constant(section.label() + " " + label(entry));
            }
            names.put(entry, scope.name(base));
        }
        return names;
    }

    /**
     * Turns a label into a constant name: ASCII upper case, a percent sign spelt out, other characters to single
     * underscores, a leading digit prefixed.
     */
    static String constant(String label)
    {
        String ascii = ascii(label.replace("%", " percent"));
        StringBuilder out = new StringBuilder(ascii.length() + 1);
        for (int i = 0; i < ascii.length(); i++)
        {
            char c = ascii.charAt(i);
            if (isAsciiLetterOrDigit(c))
            {
                out.append(Character.toUpperCase(c));
            }
            else if (out.length() > 0 && out.charAt(out.length() - 1) != '_')
            {
                out.append('_');
            }
        }
        while (out.length() > 0 && out.charAt(out.length() - 1) == '_')
        {
            out.setLength(out.length() - 1);
        }
        if (out.length() == 0)
        {
            return "UNNAMED";
        }
        if (Character.isDigit(out.charAt(0)))
        {
            out.insert(0, '_');
        }
        return out.toString();
    }

    /**
     * Turns a name into a class name: ASCII words joined in PascalCase, a leading digit prefixed.
     */
    static String className(String raw)
    {
        String ascii = ascii(raw == null ? "" : raw);
        StringBuilder out = new StringBuilder(ascii.length() + 1);
        boolean startOfWord = true;
        for (int i = 0; i < ascii.length(); i++)
        {
            char c = ascii.charAt(i);
            if (!isAsciiLetterOrDigit(c))
            {
                startOfWord = true;
                continue;
            }
            out.append(startOfWord ? Character.toUpperCase(c) : Character.toLowerCase(c));
            startOfWord = false;
        }
        if (out.length() == 0)
        {
            return "Unnamed";
        }
        if (Character.isDigit(out.charAt(0)))
        {
            out.insert(0, '_');
        }
        return out.toString();
    }

    private static String label(SettingsMenu.Entry entry)
    {
        return entry.label() == null ? "" : entry.label();
    }

    private static String entryDoc(SettingsMenu.Entry entry)
    {
        String text = entry.description().isEmpty() ? entry.label() : entry.description();
        if (text == null || text.isEmpty())
        {
            text = KEY_TYPES.get(entry.kind());
        }
        return entry.settingId() > 0 ? text + " Setting " + entry.settingId() + "." : text;
    }

    private static String doc(String text)
    {
        if (text == null)
        {
            return "";
        }
        String flat = ascii(text).replace("*/", "* /").replace('\r', ' ').replace('\n', ' ');
        StringBuilder out = new StringBuilder(flat.length());
        for (int i = 0; i < flat.length(); i++)
        {
            char c = flat.charAt(i);
            if (c >= ' ' && c <= '~')
            {
                out.append(c);
            }
        }
        return out.toString().trim();
    }

    private static String ascii(String text)
    {
        return Normalizer.normalize(text, Normalizer.Form.NFD).replaceAll("\\p{M}", "");
    }

    private static boolean isAsciiLetterOrDigit(char c)
    {
        return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
    }

    /**
     * Hands out names, suffixing one that was given out before.
     */
    private static final class UniqueNames
    {
        private final Map<String, Integer> seen = new HashMap<>();

        private String name(String wanted)
        {
            int count = seen.merge(wanted, 1, Integer::sum);
            if (count == 1)
            {
                return wanted;
            }
            String suffixed = wanted + "_" + count;
            while (seen.containsKey(suffixed))
            {
                suffixed = wanted + "_" + (++count);
            }
            seen.put(suffixed, 1);
            return suffixed;
        }
    }
}
